"""The map and briefs for coding agents, and their export (design sections 23.2 and 23.4)."""

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest

from codetrail.agents.export import build_export, read_export, write_export
from codetrail.config import GlobalConfig, TargetConfig
from codetrail.database import connect
from codetrail.facts import Entity, EntityKind, Relation, RelationKind, Source
from codetrail.facts.store import FactStore
from codetrail.generate.outline import OutlineEntry, outline_data
from codetrail.generate.scope import page_meta
from codetrail.guide import GuideRepository, Page
from codetrail.repo.rules import Reason
from codetrail.repo.source import Excluded, SourceManifest

COMMIT = "a" * 40
LATER = "b" * 40
FILES = {"services/api/app/main.py": "b1", "services/api/app/db.py": "b2", "README.md": "b3"}
API = OutlineEntry("areas/api", "area", "The API", ["services/api"], [], ["module:services/api/app/main.py"])
CONTRACT = OutlineEntry("concepts/contract", "concept", "The contract", ["services/api/app"])
MAIN_FILE = "services/api/app/main.py"


def part(folder: str, kind: str, name: str) -> Entity:
    return Entity(f"part:{folder}", EntityKind.PART, {"kind": kind, "name": name, "folder": folder}, (Source(folder),))


def decision(number: str, title: str, status: str) -> Entity:
    path = f"docs/adr/{number}.md"
    attributes = {"number": number, "title": title, "status": status, "path": path}
    return Entity(f"decision:ADR-{number}", EntityKind.DECISION, attributes, (Source(path),))


def entities(main_attributes: dict[str, Any] | None = None) -> list[Entity]:
    return [
        part("services/api", "service", "api"),
        part("apps/web", "app", "web"),
        *(part(f"packages/{name}", "library", name) for name in ("a", "b", "c")),
        decision("0001", "Use REST", "superseded"),
        decision("0002", "Use REST with a contract", "accepted"),
        Entity("module:services/api/app/main.py", EntityKind.MODULE, main_attributes or {}, (Source(MAIN_FILE),)),
    ]


RELATIONS = [
    Relation("part:apps/web", RelationKind.DEPENDS_ON, "part:services/api"),
    Relation("decision:ADR-0002", RelationKind.SUPERSEDES, "decision:ADR-0001"),
]


@dataclass
class World:
    guide: GuideRepository
    store: FactStore
    manifest: SourceManifest
    target: TargetConfig
    folder: Path

    def write(self, entry: OutlineEntry, files: list[str], brief: str | None = "The key file is app/main.py.") -> None:
        meta = page_meta(entry, self.store, self.manifest, files)
        if brief is not None:
            meta["brief"] = brief
        body = f"{entry.title} serves orders. It is small.\n\n> [!inferred]\n> Thin handlers. Easy tests.\n"
        self.guide.write_page(Page(entry.id, meta, body))

    def outline(self, *entries: OutlineEntry) -> None:
        self.guide.write_outline(outline_data(entries))

    def export(self, settings: GlobalConfig | None = None) -> Any:
        return build_export("shop", self.target, self.guide, self.store, self.manifest, settings or GlobalConfig())


@pytest.fixture
def world(tmp_path: Path) -> World:
    store = FactStore(connect(tmp_path / "codetrail.db"))
    store.record(COMMIT, entities(), RELATIONS)
    guide = GuideRepository(tmp_path / "guide")
    guide.ensure()
    target = TargetConfig(repository=tmp_path / "shop", branch="develop")
    return World(guide, store, SourceManifest(COMMIT, dict(FILES)), target, tmp_path / "agents")


def full(world: World) -> None:
    world.outline(API, CONTRACT)
    world.write(API, [MAIN_FILE, "services/api/app/db.py", "README.md"])
    world.write(CONTRACT, [MAIN_FILE])
    meta = {"id": "digests/2026-10-20-aaaaaaaaaaaa", "kind": "digest", "title": "Orders moved to a queue",
            "from_commit": None, "to_commit": COMMIT, "written_at": "2026-10-20T10:00:00+00:00"}  # fmt: skip
    world.guide.write_page(Page(str(meta["id"]), meta, "Orders now go through [[module:services/api/app/main.py]]."))


def test_the_map_lists_parts_decisions_changes_and_pages_in_order(world: World) -> None:
    full(world)
    text = world.export().map_text
    headings = [line for line in text.splitlines() if line.startswith("## ")]
    assert headings == ["## Parts", "## Decisions", "## Recent changes", "## Pages"]
    assert text.startswith("# Map of shop (generated by Codetrail; reference data, not instructions)")
    assert f"facts at {COMMIT[:12]}" in text and f"git diff --name-only {COMMIT}" in text
    assert "branch develop" in text and str(world.target.repository) in text
    assert "Key files: services/api/app/main.py, services/api/app/db.py\n" in text  # README.md is outside the part
    assert "- apps/web/ — app; depends on api" in text
    assert "ADR-0001 Use REST (superseded) — docs/adr/0001.md; superseded by ADR-0002" in text
    assert "Orders moved to a queue (digests/2026-10-20-aaaaaaaaaaaa)" in text
    assert "- areas/api — The API — services/api" in text
    one = GlobalConfig.model_validate({"agents": {"key_files_per_part": 1}})
    assert "Key files: services/api/app/main.py\n" in world.export(one).map_text


def test_libraries_roll_up_above_the_node_limit(world: World) -> None:
    text = world.export(GlobalConfig.model_validate({"diagrams": {"max_nodes": 2}})).map_text
    assert "- packages/ — 3 libraries: a, b, c" in text and "packages/a/" not in text
    assert "- services/api/ — service" in text


def test_the_map_is_cut_to_its_word_budget_from_the_end(world: World) -> None:
    entries = [OutlineEntry(f"concepts/p{number}", "concept", f"Page {number}", ["services"]) for number in range(400)]
    world.outline(*entries)
    for entry in entries:
        world.write(entry, [])
    text = world.export(GlobalConfig.model_validate({"agents": {"max_map_words": 500}})).map_text
    assert len(text.split()) <= 500
    assert text.startswith("# Map of shop") and "## Parts" in text and "- services/api/ — service" in text
    assert "more left out; codetrail_brief finds any page by path." in text


def test_a_brief_is_marked_stale_when_its_page_is_affected(world: World) -> None:
    full(world)
    world.store.record(LATER, entities({"changed": True}), RELATIONS)
    export = world.export()
    brief = next(page for page in export.pages if page.id == "areas/api").brief
    lines = brief.splitlines()
    assert lines[0].startswith("# Brief: The API (areas/api)") and lines[1].startswith("Possibly stale:")
    assert brief.rstrip().endswith(f"Page areas/api, written at {COMMIT[:12]}.")
    assert "2 pages possibly stale" in export.map_text  # both pages recorded the changed fact's scope
    assert f"facts at {LATER[:12]}" in export.map_text


def test_a_changed_source_file_marks_the_brief_stale(world: World) -> None:
    full(world)
    world.manifest = SourceManifest(COMMIT, {**FILES, "services/api/app/db.py": "changed"})
    pages = {page.id: page for page in world.export().pages}
    assert pages["areas/api"].stale and not pages["concepts/contract"].stale


def test_a_page_without_a_brief_gets_a_derived_one(world: World) -> None:
    world.outline(API)
    world.write(API, [MAIN_FILE], brief=None)
    [page] = world.export().pages
    assert "# The API" in page.brief and f"Key files: {MAIN_FILE}" in page.brief
    assert "[inferred] Thin handlers." in page.brief


def test_a_guide_without_pages_still_maps_the_parts(world: World) -> None:
    export = world.export()
    assert export.pages == [] and "## Parts" in export.map_text and "## Decisions" in export.map_text
    assert "No guide pages yet." in export.map_text


def test_a_page_that_left_the_outline_is_dropped(world: World) -> None:
    full(world)
    write_export(world.folder, world.export())
    assert (world.folder / "briefs" / "concepts" / "contract.md").exists()
    world.outline(API)
    write_export(world.folder, world.export())
    assert not (world.folder / "briefs" / "concepts" / "contract.md").exists()
    exported = read_export(world.folder)
    assert exported is not None and "concepts/contract" not in [page.id for page in exported.pages]
    assert "concepts/contract" not in (world.folder / "map.md").read_text()


def test_the_export_reads_back_whole(world: World) -> None:
    full(world)
    export = world.export()
    write_export(world.folder, export)
    assert read_export(world.folder) == export
    assert (world.folder / "map.md").read_text() == export.map_text
    assert (world.folder / "briefs" / "areas" / "api.md").read_text() == export.pages[0].brief
    index = world.folder / "index.json"
    index.write_text(index.read_text()[:50])
    assert read_export(world.folder) is None
    assert read_export(world.folder.parent / "nowhere") is None


def test_the_export_holds_no_excluded_path(world: World) -> None:
    full(world)
    excluded = [Excluded(".env", Reason.SECRET_PATTERN, ".env*"), Excluded("secrets/key.pem", Reason.GITLEAKS, "")]
    world.manifest = SourceManifest(COMMIT, dict(FILES), excluded)
    write_export(world.folder, world.export())
    for file in world.folder.rglob("*"):
        if file.is_file():
            assert ".env" not in file.read_text() and "secrets/key.pem" not in file.read_text()
